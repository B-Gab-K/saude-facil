const { chromium, expect } = require(process.cwd() + '/node_modules/@playwright/test');
const AxeBuilder = require(process.cwd() + '/node_modules/@axe-core/playwright').default;
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs');
const { resolve } = require('node:path');
const origin = process.argv[2];
if (!origin || new URL(origin).origin !== origin || new URL(origin).protocol !== 'https:') throw new Error('Informe a origem pública HTTPS exata da demonstração.');
const secret = name => process.env[name.toUpperCase()] || readFileSync(resolve('..', 'deploy/secrets/demo', name), 'utf8').trim();
let browser, step = 'abrir navegador';
(async () => {
  browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage(); page.setDefaultTimeout(25000);
  step = 'abrir HTTPS público';
  const response = await page.goto(origin + '/index.html', { waitUntil: 'networkidle', timeout: 45000 });
  expect(response.status()).toBe(200);
  await expect(page.getByRole('complementary', { name: 'Ambiente de demonstração' })).toBeVisible();
  expect(new URL(page.url()).protocol).toBe('https:');
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/demo-publica-inicio.png', fullPage: true });
  step = 'acessibilidade do aviso de demonstração';
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
  expect(axe.violations.map(item => item.id)).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const login = async (email, passwordFile, destination) => {
    await page.goto(origin + '/login.html');
    await page.getByLabel('E-mail', { exact: true }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill(secret(passwordFile));
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    await page.waitForURL('**/' + destination);
  };
  const logout = async () => {
    const button = page.getByRole('button', { name: 'Sair', exact: true });
    if (!await button.isVisible()) await page.locator('.nav-toggle').click();
    await button.click(); await page.waitForURL('**/login.html');
  };
  step = 'login de paciente e cookie seguro';
  await login('paciente@example.test', 'demo_patient_password', 'historico.html');
  const cookies = await context.cookies();
  const cookie = cookies.find(item => item.name === '__Host-sf_session');
  expect(cookie.secure && cookie.httpOnly && cookie.sameSite === 'Strict').toBe(true);
  step = 'reserva pelo endereço público';
  await page.goto(origin + '/agendamento.html');
  await page.getByLabel('Unidade', { exact: true }).selectOption({ label: 'Unidade Fictícia — Demonstração' });
  await page.getByLabel('Serviço', { exact: true }).selectOption({ label: 'Atendimento fictício' });
  await expect(page.locator('#horario')).toBeEnabled();
  await page.locator('#horario').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Confirmar agendamento', exact: true }).click();
  await page.waitForURL('**/confirmacao.html?*');
  await expect(page.getByText('Horário confirmado', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/demo-publica-confirmacao.png', fullPage: true });
  step = 'reagendamento pelo endereço público';
  await page.goto(origin + '/historico.html');
  await page.getByRole('link', { name: 'Reagendar', exact: true }).click();
  await expect(page.locator('#horario')).toBeEnabled();
  await page.locator('#horario').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Confirmar reagendamento', exact: true }).click();
  await page.waitForURL('**/confirmacao.html?*');
  step = 'cancelamento pelo endereço público';
  await page.goto(origin + '/historico.html');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByText(/O agendamento foi cancelado/)).toBeVisible();
  step = 'acesso profissional pelo endereço público';
  await logout();
  await login('recepcao@example.test', 'demo_staff_password', 'painel-profissional.html');
  const management = await page.request.get(origin + '/api/catalog/management'); expect(management.status()).toBe(403);
  await logout();
  const result = { date: new Date().toISOString(), origin, publicHttps: true, demoBanner: true, secureCookies: true, patientLogin: true, booking: true, reschedule: true, cancellation: true, professionalLogin: true, receptionCannotManage: true, automatedAccessibilityOnDemoHome: true, device: 'Chromium automatizado; viewport 390x844; mesma máquina de execução' };
  writeFileSync('test-results/demo-publica.json', JSON.stringify(result, null, 2));
  process.stdout.write(JSON.stringify(result) + '\n');
})().catch(error => { console.error(JSON.stringify({ step, error: error.name })); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
